/**
 * Dossier planning: decides what every document in a dossier says, and what is
 * wrong with it, before anything is rendered to disk.
 *
 * Planning is separated from rendering so ground truth is computed once, from a
 * single source, and the PDF/image writers become pure functions of the plan.
 * It also means the corpus can be re-planned and diffed without producing files.
 *
 * ## Why every dossier carries its own reference date
 *
 * Freshness is relative to "now". If the corpus were generated against the wall
 * clock, a dossier planned as `fresh` today would silently become `expired` next
 * month and the committed ground truth would rot. Instead each dossier fixes a
 * `referenceDate`, and the pipeline is evaluated *as of* that date. The corpus
 * stays valid indefinitely.
 */

import { addDays, type PlainDate } from "@/lib/dates";
import type {
  CedulaFields,
  CertificacionDgiiFields,
  CertificacionTssFields,
  ComplianceStatus,
  DocumentType,
  RegistroMercantilFields,
} from "@/lib/domain/types";
import { DOCUMENT_TYPES } from "@/lib/domain/types";
import { VALIDITY_WINDOW_DAYS } from "@/lib/config";

import {
  generateCedula,
  generateCodigoVerificacion,
  generateInvalidCedula,
  generateInvalidRnc,
  generateNumeroRegistro,
  generateRnc,
} from "./identifiers";
import { generateCompany, generatePersonName, restyleCompanyName, type SyntheticCompany } from "./pools";
import { createRng, type Rng } from "./random";
import {
  COMBINABLE_DEFECTS,
  DGII_STATUS_PHRASINGS,
  TSS_STATUS_PHRASINGS,
  type DateScenario,
  type Defect,
  type DefectKind,
} from "./scenarios";

/** The date the whole corpus is centred on; each dossier jitters around it. */
const CORPUS_REFERENCE_DATE: PlainDate = "2026-06-15";

/** How far a dossier's reference date may drift from the corpus centre. */
const REFERENCE_JITTER_DAYS = 90;

/** Severity the dossier is expected to reach because of a given defect. */
export type DefectSeverity = "warn" | "fail";

export interface PlannedDefect extends Defect {
  severity: DefectSeverity;
}

interface DocumentBase {
  /** Output filename. Deliberately uninformative — the classifier gets no hints. */
  filename: string;
  /**
   * Seed for incidental render choices (signatory names).
   *
   * Attached to the document rather than derived from its position, so a
   * duplicated document renders to identical bytes. Keying it on the array index
   * gave the copy a different signatory, turning "the same file attached twice"
   * into "two different documents of the same type" — and defeating hash-based
   * duplicate detection.
   */
  renderSeed: number;
}

export type PlannedDocument =
  | (DocumentBase & {
      type: "registro_mercantil";
      fields: RegistroMercantilFields;
      city: string;
    })
  | (DocumentBase & {
      type: "certificacion_dgii";
      fields: CertificacionDgiiFields;
      /** The prose the status is expressed in, chosen from the phrasing pool. */
      phrasing: string;
    })
  | (DocumentBase & {
      type: "certificacion_tss";
      fields: CertificacionTssFields;
      phrasing: string;
    })
  | (DocumentBase & {
      type: "cedula";
      fields: CedulaFields;
      /** Degradation applied when rasterising, so the render stays reproducible. */
      degradation: DegradationSpec;
    });

/** Image degradation parameters for a scanned cedula. */
export interface DegradationSpec {
  /** Rotation in degrees, within ±5 as specified for the corpus. */
  rotationDegrees: number;
  /** Gaussian noise sigma. */
  noiseSigma: number;
  /**
   * Seed for the grain.
   *
   * The noise is generated by this project rather than by libvips, whose
   * `gaussnoise` takes no seed and produces different pixels on every run. That
   * silently broke the promise that a given corpus seed reproduces the corpus
   * byte for byte — the PDFs were reproducible, the cedulas never were.
   */
  noiseSeed: number;
  /** JPEG quality, low enough to leave visible artefacts. */
  jpegQuality: number;
  /** Strength of the simulated uneven lighting gradient, in `[0, 1]`. */
  lightingStrength: number;
  /** Fraction of the image cropped away at one edge, in `[0, 0.12]`. */
  cropFraction: number;
}

/**
 * A condition that legitimately produces a warning without being an injected
 * defect — currently only a document sitting inside the expiry warning band.
 *
 * Kept separate from `defects` on purpose. A certification four days from expiry
 * is not defective: nothing was corrupted, the supplier simply needs to renew it
 * soon. Folding it into `defects` would misreport the corpus's clean/defective
 * split; leaving it out of the expected verdict, as an earlier version did, made
 * the ground truth claim `pass` for ten dossiers the rules correctly warned on.
 */
export interface ExpectedWarning {
  documentType: DocumentType;
  reason: "near_expiry";
  detail: string;
}

export interface DossierPlan {
  id: string;
  seed: number;
  referenceDate: PlainDate;
  company: SyntheticCompany;
  representanteLegal: string;
  documents: PlannedDocument[];
  defects: PlannedDefect[];
  expectedWarnings: ExpectedWarning[];
  expectedVerdict: "pass" | "warn" | "fail";
}

/* ------------------------------------------------------------------ dates -- */

/**
 * Issue date for a certification whose expiry is implicit (DGII, TSS).
 *
 * Offsets are chosen so each scenario lands unambiguously inside its band and
 * never on a boundary — a fixture sitting exactly on the expiry threshold would
 * make a legitimate off-by-one in the validator look like a coin flip.
 */
function issueDateForImplicitExpiry(
  rng: Rng,
  reference: PlainDate,
  windowDays: number,
  scenario: DateScenario,
  warningDays: number,
): PlainDate {
  switch (scenario) {
    case "fresh":
      // Expires more than `warningDays` from now.
      return addDays(reference, -rng.int(0, windowDays - warningDays - 1));
    case "near_expiry":
      // Expires within the warning band, still valid today.
      return addDays(reference, -rng.int(windowDays - warningDays, windowDays));
    case "expired":
      return addDays(reference, -rng.int(windowDays + 1, windowDays + 170));
    case "future_issue":
      return addDays(reference, rng.int(1, 30));
  }
}

/** Issue and expiry for the Registro Mercantil, which prints its own expiry. */
function registroMercantilDates(
  rng: Rng,
  reference: PlainDate,
  scenario: DateScenario,
  warningDays: number,
): { emision: PlainDate; vencimiento: PlainDate } {
  const validityDays = rng.pick([365, 730]);

  if (scenario === "future_issue") {
    const emision = addDays(reference, rng.int(5, 60));
    return { emision, vencimiento: addDays(emision, validityDays) };
  }

  // The expiry must stay within one validity period of the reference date, or
  // the derived issue date lands in the future and a dossier planned as clean
  // silently acquires a future-issue defect.
  const freshCeiling = Math.min(500, validityDays - 1);

  const vencimiento =
    scenario === "fresh"
      ? addDays(reference, rng.int(warningDays + 1, freshCeiling))
      : scenario === "near_expiry"
        ? addDays(reference, rng.int(0, warningDays))
        : addDays(reference, -rng.int(1, 300));

  return { emision: addDays(vencimiento, -validityDays), vencimiento };
}

/* -------------------------------------------------------------- filenames -- */

const PDF_FILENAME_SHAPES = [
  (rng: Rng) => `ESCANEO_${String(rng.int(1, 9999)).padStart(4, "0")}.pdf`,
  (rng: Rng) => `SCAN${String(rng.int(1, 9999)).padStart(4, "0")}.pdf`,
  (rng: Rng) => `Documento_${rng.int(1, 40)}.pdf`,
  (rng: Rng) => `doc${rng.int(1, 99)}.pdf`,
  (rng: Rng) => `archivo (${rng.int(1, 12)}).pdf`,
  (rng: Rng) =>
    `CamScanner ${String(rng.int(1, 28)).padStart(2, "0")}-${String(rng.int(1, 12)).padStart(2, "0")}-2026.pdf`,
];

const IMAGE_FILENAME_SHAPES = [
  (rng: Rng) => `IMG_${String(rng.int(1, 9999)).padStart(4, "0")}.jpg`,
  (rng: Rng) => `foto_${rng.int(1, 99)}.jpg`,
  (rng: Rng) => `WhatsApp Image 2026-0${rng.int(1, 9)}-${String(rng.int(10, 28))}.jpeg`,
  (rng: Rng) => `20260${rng.int(1, 9)}${String(rng.int(10, 28))}_${rng.int(100000, 999999)}.jpg`,
];

/**
 * Filenames carry no type information by design: §7 requires the classifier to
 * work from content alone, so a name like `certificacion_dgii.pdf` would let the
 * pipeline cheat and would make the classification metric meaningless.
 */
function makeFilenameFactory(rng: Rng) {
  const used = new Set<string>();

  return (kind: "pdf" | "image"): string => {
    const shapes = kind === "pdf" ? PDF_FILENAME_SHAPES : IMAGE_FILENAME_SHAPES;
    for (let attempt = 0; attempt < 50; attempt++) {
      const candidate = rng.pick(shapes)(rng);
      if (!used.has(candidate)) {
        used.add(candidate);
        return candidate;
      }
    }
    // Deterministic fallback; reaching it means the shape pool is too small.
    const fallback = `archivo_${used.size + 1}.${kind === "pdf" ? "pdf" : "jpg"}`;
    used.add(fallback);
    return fallback;
  };
}

/* ------------------------------------------------------------------- plan -- */

function degradationFor(rng: Rng): DegradationSpec {
  return {
    rotationDegrees: rng.float(-5, 5),
    noiseSigma: rng.float(4, 18),
    noiseSeed: rng.int(1, 2_147_483_646),
    jpegQuality: rng.int(38, 72),
    lightingStrength: rng.float(0.1, 0.55),
    cropFraction: rng.bool(0.35) ? rng.float(0.02, 0.12) : 0,
  };
}

/** Introduce a single-character typo, used to build near-miss name defects. */
function typo(rng: Rng, text: string): string {
  const letters = [...text];
  const positions = letters
    .map((char, index) => (/[a-záéíóúñ]/i.test(char) ? index : -1))
    .filter((index) => index >= 0);
  if (positions.length === 0) return text;
  const at = rng.pick(positions);
  // Substitutions that stay phonetically plausible, so the result reads like a
  // transcription slip rather than random corruption.
  const substitutes: Record<string, string> = {
    c: "k",
    s: "z",
    b: "v",
    y: "i",
    v: "b",
    z: "s",
    k: "c",
  };
  const current = letters[at].toLowerCase();
  letters[at] = substitutes[current] ?? (current === "a" ? "e" : "a");
  return letters.join("");
}

export interface PlanOptions {
  id: string;
  seed: number;
  /**
   * Exactly which defects to inject; empty for a clean dossier.
   *
   * Chosen by the corpus generator rather than drawn here, so the whole corpus
   * can be stratified. Letting each dossier draw independently left some defect
   * kinds with a single instance across 40 dossiers, which makes any per-defect
   * detection rate in the eval statistically meaningless.
   */
  defectKinds: readonly DefectKind[];
  expiryWarningDays: number;
}

export function planDossier(options: PlanOptions): DossierPlan {
  const rng = createRng(options.seed);
  const { expiryWarningDays } = options;

  const referenceDate = addDays(
    CORPUS_REFERENCE_DATE,
    rng.int(-REFERENCE_JITTER_DAYS, REFERENCE_JITTER_DAYS),
  );

  const company = generateCompany(rng);
  const representanteLegal = generatePersonName(rng);
  const rnc = generateRnc(rng);
  const nextFilename = makeFilenameFactory(rng);

  const defects: PlannedDefect[] = [];
  const has = (kind: DefectKind) => options.defectKinds.includes(kind);

  /* --- identifiers, possibly corrupted --------------------------------- */

  const registroRnc = has("invalid_rnc_check_digit") ? generateInvalidRnc(rng) : rnc;
  if (has("invalid_rnc_check_digit")) {
    defects.push({
      kind: "invalid_rnc_check_digit",
      documentType: "registro_mercantil",
      severity: "fail",
      detail: `RNC ${registroRnc} has a deliberately wrong check digit`,
    });
  }

  // A mismatch is applied to the DGII copy so the coherence check has something
  // to disagree about while the Registro Mercantil stays authoritative.
  const dgiiRnc = has("rnc_mismatch") ? generateRnc(rng) : registroRnc;
  if (has("rnc_mismatch")) {
    defects.push({
      kind: "rnc_mismatch",
      documentType: "certificacion_dgii",
      severity: "fail",
      detail: `DGII reports RNC ${dgiiRnc} while the Registro Mercantil reports ${registroRnc}`,
    });
  }

  /* --- company name across documents ------------------------------------ */

  const registroRazonSocial = company.full;
  const tssRazonSocial = restyleCompanyName(rng, company);

  let dgiiRazonSocial = restyleCompanyName(rng, company);
  if (has("razon_social_mismatch")) {
    // Two flavours: a typo that must surface as a warning, and an outright
    // different company that must fail.
    if (rng.bool(0.5)) {
      dgiiRazonSocial = `${typo(rng, company.base)} ${company.legalForm}`;
      defects.push({
        kind: "razon_social_mismatch",
        documentType: "certificacion_dgii",
        severity: "warn",
        detail: `DGII razón social "${dgiiRazonSocial}" is a near-miss against "${registroRazonSocial}"`,
      });
    } else {
      dgiiRazonSocial = generateCompany(rng).full;
      defects.push({
        kind: "razon_social_mismatch",
        documentType: "certificacion_dgii",
        severity: "fail",
        detail: `DGII razón social "${dgiiRazonSocial}" is a different company from "${registroRazonSocial}"`,
      });
    }
  }

  /* --- representative and cedula ---------------------------------------- */

  let cedulaNombre = representanteLegal;
  if (has("representante_mismatch")) {
    cedulaNombre = generatePersonName(rng);
    defects.push({
      kind: "representante_mismatch",
      documentType: "cedula",
      severity: "fail",
      detail: `Cédula names "${cedulaNombre}" but the Registro Mercantil names "${representanteLegal}"`,
    });
  }

  const cedulaNumero = has("invalid_cedula_check_digit")
    ? generateInvalidCedula(rng)
    : generateCedula(rng);
  if (has("invalid_cedula_check_digit")) {
    defects.push({
      kind: "invalid_cedula_check_digit",
      documentType: "cedula",
      severity: "fail",
      detail: `Cédula ${cedulaNumero} has a deliberately wrong check digit`,
    });
  }

  /* --- date scenarios ---------------------------------------------------- */

  const expiredTarget: DocumentType | null = has("expired_document")
    ? rng.pick(["registro_mercantil", "certificacion_dgii", "certificacion_tss"] as const)
    : null;
  const futureTarget: DocumentType | null = has("future_issue_date")
    ? rng.pick(["registro_mercantil", "certificacion_dgii", "certificacion_tss"] as const)
    : null;

  const expectedWarnings: ExpectedWarning[] = [];

  const scenarioFor = (type: DocumentType): DateScenario => {
    if (expiredTarget === type) return "expired";
    if (futureTarget === type) return "future_issue";

    // A minority of otherwise-clean documents sit in the warning band, which is
    // what gives the corpus `warn` cases that are not defects. Recording it is
    // what keeps the expected verdict honest.
    if (rng.bool(0.15)) {
      expectedWarnings.push({
        documentType: type,
        reason: "near_expiry",
        detail: `${type} expires within the ${expiryWarningDays}-day warning band as of ${referenceDate}`,
      });
      return "near_expiry";
    }

    return "fresh";
  };

  if (expiredTarget) {
    defects.push({
      kind: "expired_document",
      documentType: expiredTarget,
      severity: "fail",
      detail: `${expiredTarget} is expired as of ${referenceDate}`,
    });
  }
  if (futureTarget) {
    defects.push({
      kind: "future_issue_date",
      documentType: futureTarget,
      severity: "fail",
      detail: `${futureTarget} carries an issue date after ${referenceDate}`,
    });
  }

  const rmScenario = scenarioFor("registro_mercantil");
  const rmDates = registroMercantilDates(rng, referenceDate, rmScenario, expiryWarningDays);

  const dgiiEmision = issueDateForImplicitExpiry(
    rng,
    referenceDate,
    VALIDITY_WINDOW_DAYS.certificacion_dgii,
    scenarioFor("certificacion_dgii"),
    expiryWarningDays,
  );
  const tssEmision = issueDateForImplicitExpiry(
    rng,
    referenceDate,
    VALIDITY_WINDOW_DAYS.certificacion_tss,
    scenarioFor("certificacion_tss"),
    expiryWarningDays,
  );

  /* --- compliance status -------------------------------------------------- */

  let dgiiEstado: ComplianceStatus = "al_dia";
  let tssEstado: ComplianceStatus = "al_dia";

  if (has("status_not_al_dia")) {
    const target = rng.pick(["certificacion_dgii", "certificacion_tss"] as const);
    const value: ComplianceStatus = rng.pick(["con_deuda", "indeterminado"] as const);
    if (target === "certificacion_dgii") dgiiEstado = value;
    else tssEstado = value;
    defects.push({
      kind: "status_not_al_dia",
      documentType: target,
      severity: "fail",
      detail: `${target} reports estado "${value}"`,
    });
  }

  /* --- cedula dates -------------------------------------------------------- */

  const cedulaVencida = has("expired_cedula");
  if (cedulaVencida) {
    defects.push({
      kind: "expired_cedula",
      documentType: "cedula",
      severity: "fail",
      detail: `Cédula expired before ${referenceDate}`,
    });
  }

  /* --- assemble documents --------------------------------------------------- */

  const documents: PlannedDocument[] = [
    {
      type: "registro_mercantil",
      filename: nextFilename("pdf"),
      renderSeed: rng.int(1, 2_147_483_646),
      city: company.city,
      fields: {
        rnc: registroRnc,
        razon_social: registroRazonSocial,
        numero_registro: generateNumeroRegistro(rng),
        fecha_emision: rmDates.emision,
        fecha_vencimiento: rmDates.vencimiento,
        representante_legal: representanteLegal,
      },
    },
    {
      type: "certificacion_dgii",
      filename: nextFilename("pdf"),
      renderSeed: rng.int(1, 2_147_483_646),
      phrasing: rng.pick(DGII_STATUS_PHRASINGS[dgiiEstado]),
      fields: {
        rnc: dgiiRnc,
        razon_social: dgiiRazonSocial,
        estado: dgiiEstado,
        fecha_emision: dgiiEmision,
        codigo_verificacion: generateCodigoVerificacion(rng),
      },
    },
    {
      type: "certificacion_tss",
      filename: nextFilename("pdf"),
      renderSeed: rng.int(1, 2_147_483_646),
      phrasing: rng.pick(TSS_STATUS_PHRASINGS[tssEstado]),
      fields: {
        rnc: registroRnc,
        razon_social: tssRazonSocial,
        estado: tssEstado,
        fecha_emision: tssEmision,
      },
    },
    {
      type: "cedula",
      filename: nextFilename("image"),
      renderSeed: rng.int(1, 2_147_483_646),
      degradation: degradationFor(rng),
      fields: {
        cedula: cedulaNumero,
        nombre_completo: cedulaNombre,
        fecha_nacimiento: addDays(referenceDate, -rng.int(20 * 365, 65 * 365)),
        fecha_vencimiento: cedulaVencida
          ? addDays(referenceDate, -rng.int(1, 500))
          : addDays(referenceDate, rng.int(200, 3000)),
      },
    },
  ];

  /* --- structural defects --------------------------------------------------- */

  let finalDocuments = documents;

  if (has("missing_document")) {
    const dropped = rng.pick(DOCUMENT_TYPES);
    finalDocuments = finalDocuments.filter((doc) => doc.type !== dropped);
    defects.push({
      kind: "missing_document",
      documentType: dropped,
      severity: "fail",
      detail: `Dossier is missing the ${dropped} document`,
    });
  }

  if (has("duplicate_document")) {
    const duplicated = rng.pick(finalDocuments);
    const copy: PlannedDocument = {
      ...duplicated,
      filename: nextFilename(duplicated.type === "cedula" ? "image" : "pdf"),
    };
    finalDocuments = [...finalDocuments, copy];
    defects.push({
      kind: "duplicate_document",
      documentType: duplicated.type,
      severity: "warn",
      detail: `Dossier contains two copies of the ${duplicated.type} document`,
    });
  }

  return {
    id: options.id,
    seed: options.seed,
    referenceDate,
    company,
    representanteLegal,
    documents: rng.shuffle(finalDocuments),
    defects,
    // Warnings from documents that were dropped are not observable, so they must
    // not influence the expected verdict.
    expectedWarnings: expectedWarnings.filter((w) =>
      finalDocuments.some((d) => d.type === w.documentType),
    ),
    expectedVerdict: defects.some((d) => d.severity === "fail")
      ? "fail"
      : defects.some((d) => d.severity === "warn") ||
          expectedWarnings.some((w) => finalDocuments.some((d) => d.type === w.documentType))
        ? "warn"
        : "pass",
  };
}

/**
 * Deal defect kinds across the defective dossiers so every kind is represented
 * a comparable number of times.
 *
 * Structural defects are dealt their own dossiers: they remove or duplicate a
 * whole document, and pairing one with a coherence defect on the same document
 * would make the second unobservable rather than merely harder to catch.
 */
export function assignDefects(rng: Rng, defectiveCount: number): DefectKind[][] {
  if (defectiveCount <= 0) return [];

  const structuralTotal = Math.min(defectiveCount, Math.max(2, Math.round(defectiveCount * 0.22)));
  const missingCount = Math.ceil(structuralTotal / 2);

  const assignments: DefectKind[][] = [
    ...Array.from({ length: missingCount }, (): DefectKind[] => ["missing_document"]),
    ...Array.from({ length: structuralTotal - missingCount }, (): DefectKind[] => [
      "duplicate_document",
    ]),
  ];

  const remaining = defectiveCount - structuralTotal;
  // Around a third of the remaining dossiers carry two defects at once, so the
  // cross-check has to cope with more than one thing being wrong.
  const doubles = Math.round(remaining * 0.3);

  // A round-robin deck rather than independent draws: this is what guarantees
  // near-equal representation instead of merely expecting it.
  const deck: DefectKind[] = [];
  for (let i = 0; deck.length < remaining + doubles; i++) {
    deck.push(COMBINABLE_DEFECTS[i % COMBINABLE_DEFECTS.length]);
  }
  const shuffled = rng.shuffle(deck);

  let cursor = 0;
  for (let i = 0; i < remaining; i++) {
    const wanted = i < doubles ? 2 : 1;
    const picked: DefectKind[] = [];
    let scanned = 0;

    while (picked.length < wanted && scanned < shuffled.length) {
      const kind = shuffled[(cursor + scanned) % shuffled.length];
      scanned++;
      if (!picked.includes(kind)) {
        picked.push(kind);
        cursor = (cursor + scanned) % shuffled.length;
        scanned = 0;
      }
    }

    assignments.push(picked);
  }

  return rng.shuffle(assignments);
}
